const byId = <T extends { id: string }>(items: T[], id: string) => items.find((i) => i.id === id)!;

function seedBooking(
  id: string,
  listingId: string,
  borrowerId: string,
  days: number,
  startOffset: number,
  history: Booking['status'][],
  extra: Partial<Booking> = {},
): Booking {
  const listing = byId(LISTINGS, listingId);
  const borrower = byId(USERS, borrowerId);
  return {
    id,
    listingId,
    borrowerId,
    days,
    start: addDays(today, startOffset),
    quote: quote(listing, days, borrower),
    status: history[history.length - 1],
    history: history.map((status, i) => ({ status, at: daysAgo(history.length - i) })),
    ...extra,
  };
}

